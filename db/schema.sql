-- ---------------------------------------------------------------------
-- Legacy cleanup (safe no-ops if they were never created)
-- ---------------------------------------------------------------------
-- An earlier build installed pg_trgm + GIN indexes in the public schema for
-- title search. Runtime search now runs in-memory in the Node server, so the
-- extension is unnecessary and trips the "Extension in Public" advisor. Drop
-- the dependent indexes first, then the extension. `if exists` = harmless when
-- they aren't present.
drop index if exists public.games_title_trgm_idx;
drop index if exists public.games_title_fts_idx;
drop extension if exists pg_trgm cascade;


-- ---------------------------------------------------------------------
-- Table (created only if it doesn't already exist — your data is kept)
-- ---------------------------------------------------------------------
create table if not exists public.games (
  id            bigint generated by default as identity primary key,
  slug          text         not null unique,
  title         varchar(255) not null,
  game_url      text         not null,
  thumbnail_url text,
  category      text         not null default 'arcade',
  is_working    boolean      not null default true,
  last_checked  timestamptz  not null default now(),
  created_at    timestamptz  not null default now(),
  updated_at    timestamptz  not null default now()
);

-- Backfill any columns that an older version of the table might be missing,
-- without touching existing rows. (No-ops once the column is present.)
alter table public.games add column if not exists thumbnail_url text;
alter table public.games add column if not exists category     text        not null default 'arcade';
alter table public.games add column if not exists is_working   boolean     not null default true;
alter table public.games add column if not exists last_checked timestamptz not null default now();
alter table public.games add column if not exists created_at   timestamptz not null default now();
alter table public.games add column if not exists updated_at   timestamptz not null default now();

comment on table  public.games               is 'ZoFHub game catalog — source of truth for /api/games. Updated by hourly cron.';
comment on column public.games.slug          is 'URL-safe stable identifier. UNIQUE — primary dedupe key across sources.';
comment on column public.games.title         is 'Display name. Max 255 chars.';
comment on column public.games.game_url      is 'Publisher iframe src — used by /play/:slug as the iframe target.';
comment on column public.games.thumbnail_url is 'Image URL. NULL → frontend swaps to /default-placeholder.svg.';
comment on column public.games.category      is 'Free-form category slug (puzzle / racing / arcade / etc). Default = arcade.';
comment on column public.games.is_working    is 'Set false by hourly link-check when HEAD returns 4xx/5xx/timeout.';
comment on column public.games.last_checked  is 'Last time link-check probed game_url. Cron uses this for ASC ordering.';
comment on column public.games.created_at    is 'First seen by migration.';
comment on column public.games.updated_at    is 'Auto-bumped on every UPDATE by trg_games_updated_at trigger.';


-- ---------------------------------------------------------------------
-- Indexes — cover the queries the server + cron actually run.
-- (Runtime title search is in-memory in Node, so no GIN/trigram index here.)
-- ---------------------------------------------------------------------

-- Hot read: WHERE is_working = true ORDER BY id DESC LIMIT N OFFSET X
create index if not exists games_working_id_desc_idx
  on public.games (is_working, id desc);

-- Cron: WHERE is_working = true ORDER BY last_checked ASC LIMIT N
create index if not exists games_working_lastchecked_idx
  on public.games (is_working, last_checked asc);

-- Category pages: WHERE category = $1 (only working rows).
create index if not exists games_category_idx
  on public.games (category) where is_working = true;

-- NOTE: the UNIQUE constraint on `slug` already creates a btree index.


-- ---------------------------------------------------------------------
-- updated_at auto-bump trigger
-- ---------------------------------------------------------------------
-- SECURITY INVOKER + empty search_path is the Supabase-recommended hardening
-- (clears the "Function Search Path Mutable" advisor). now() resolves from
-- pg_catalog, which is always implicitly available even with search_path = ''.
create or replace function public.games_set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_games_updated_at on public.games;
create trigger trg_games_updated_at
  before update on public.games
  for each row execute function public.games_set_updated_at();


-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
-- Anon / publishable key may only READ working games. The service-role key
-- (used by the Node server for cron link-check + migration) bypasses RLS.
alter table public.games enable row level security;

drop policy if exists "Public can read working games" on public.games;
create policy "Public can read working games"
  on public.games for select
  using (is_working = true);


-- ---------------------------------------------------------------------
-- Frontend-shaped view (SECURITY INVOKER so it respects the caller's RLS)
-- ---------------------------------------------------------------------
-- `games_public` is what /api/games queries. It pre-applies the is_working
-- filter and substitutes a placeholder when thumbnail is NULL/empty.
create or replace view public.games_public
with (security_invoker = true) as
  select
    id,
    slug,
    title,
    game_url,
    coalesce(nullif(thumbnail_url, ''), '/default-placeholder.svg') as thumbnail_url,
    category,
    last_checked
  from public.games
  where is_working = true;

comment on view public.games_public is 'Frontend projection of public.games — pre-filtered to is_working=true with thumbnail fallback. SECURITY INVOKER.';


