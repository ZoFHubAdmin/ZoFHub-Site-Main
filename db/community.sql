-- =====================================================================
-- ZoFHub · community schema  (recommendations + leaderboard)
-- =====================================================================
-- ADDITIVE & SAFE: uses CREATE TABLE IF NOT EXISTS and touches NOTHING in
-- the existing `games` table. Run it once in the Supabase SQL Editor:
--   Dashboard → SQL Editor → New query → paste → Run.
--
-- Two tables:
--   recommendations — user-submitted "you should add/play this" entries,
--                     each with an embeddable game URL + a short note.
--   scores          — player-reported leaderboard entries per game.
--
-- Security model (matches the rest of ZoFHub):
--   * RLS ON. Public (anon key) may only SELECT.
--   * All writes go through the Node server using the SERVICE-ROLE key,
--     which bypasses RLS — so the server can validate/sanitize every insert
--     (trusted-host check on embed_url, length limits, rate basics) before
--     it ever reaches the DB. The browser can never write directly.
-- =====================================================================

-- ---------------------------------------------------------------------
-- recommendations
-- ---------------------------------------------------------------------
create table if not exists public.recommendations (
  id          bigint generated by default as identity primary key,
  title       varchar(120) not null,
  embed_url   text         not null,
  note        varchar(280),
  author      varchar(40)  not null default 'Anonymous',
  category    text         not null default 'arcade',
  views       integer      not null default 0,
  is_visible  boolean      not null default true,
  created_at  timestamptz  not null default now(),
  last_seen_at timestamptz not null default now()
);

comment on table public.recommendations is 'Community-submitted game recommendations. Embed URLs are validated against the trusted-host allowlist server-side before insert.';

-- Feed ordering: newest visible first.
create index if not exists recommendations_visible_created_idx
  on public.recommendations (is_visible, created_at desc);
-- Cleanup ordering: find least-viewed / oldest cheaply.
create index if not exists recommendations_views_created_idx
  on public.recommendations (views asc, created_at asc);

alter table public.recommendations enable row level security;
drop policy if exists "Public can read visible recommendations" on public.recommendations;
create policy "Public can read visible recommendations"
  on public.recommendations for select using (is_visible = true);

-- ---------------------------------------------------------------------
-- scores (leaderboard)
-- ---------------------------------------------------------------------
create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  slug        text         not null,
  player_name varchar(40)  not null default 'Player',
  score       bigint       not null default 0,
  created_at  timestamptz  not null default now()
);

comment on table public.scores is 'Player-reported leaderboard scores per game slug.';

-- Per-game leaderboard: WHERE slug = $1 ORDER BY score DESC.
create index if not exists scores_slug_score_idx on public.scores (slug, score desc);
-- Global leaderboard: ORDER BY score DESC.
create index if not exists scores_score_idx on public.scores (score desc);
-- Best-per-player lookup: the score POST does WHERE slug = $1 AND player_name = $2
-- (keep-best dedupe). This index makes that exact lookup an index seek.
create index if not exists scores_slug_player_idx on public.scores (slug, player_name);

alter table public.scores enable row level security;
drop policy if exists "Public can read scores" on public.scores;
create policy "Public can read scores"
  on public.scores for select using (true);

-- ---------------------------------------------------------------------
-- prune_scores() — keep the leaderboard BOUNDED so storage can't run away.
-- Keeps only the top `keep_per_game` scores per game (by score, oldest-first as
-- the tiebreak) and deletes the long tail nobody ever sees — the UI only shows
-- the top ~20-50. Together with the one-row-per-(game,player) keep-best dedupe
-- the score API already enforces, this hard-caps the table at roughly
-- keep_per_game × (number of games with scores) rows, each only ~80 bytes.
-- A single set-based statement (fast with the scores_slug_score_idx index).
-- Called daily by the Node cron via RPC: supa.rpc('prune_scores', {...}).
-- SECURITY DEFINER so the service role can run it; not exposed to anon.
-- ---------------------------------------------------------------------
create or replace function public.prune_scores(keep_per_game integer default 200)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  removed integer;
begin
  with ranked as (
    select id,
           row_number() over (partition by slug order by score desc, created_at asc) as rn
    from public.scores
  )
  delete from public.scores s
  using ranked r
  where s.id = r.id and r.rn > keep_per_game;
  get diagnostics removed = row_count;
  return removed;
end;
$$;

-- Only the server (service role / postgres) may prune; never the public anon key.
revoke all on function public.prune_scores(integer) from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- Sanity check
-- ---------------------------------------------------------------------
select
  (select count(*) from public.recommendations) as recommendations,
  (select count(*) from public.scores)          as scores;
